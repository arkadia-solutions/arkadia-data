#!/usr/bin/env bash
# Regenerates skills/ak-data-format/reference/ from the ak-data binary, so the
# skill's reference is always what the decoder does:
#   spec.md      `ak-data info` (every example decoded live)
#   examples.md  the `ak-data example` gallery: AK-DATA, JSON, question, answer
set -euo pipefail
cd "$(dirname "$0")/.."
BIN=${BIN:-rust/target/release/ak-data}
OUT=skills/ak-data-format/reference
mkdir -p "$OUT"

{
  echo "# AK-DATA — the complete definition"
  echo
  echo "Generated by \`ak-data info\` ($("$BIN" --version --no-color | awk '{print $2}')). Every example is decoded"
  echo "by the reference decoder; the line after \`→\` is the JSON it means."
  echo
  echo '```text'
  "$BIN" info --no-color
  echo '```'
} > "$OUT/spec.md"

{
  echo "# AK-DATA examples"
  echo
  echo "Generated from \`ak-data example\`. Each example: what it shows, the AK-DATA,"
  echo "the same data as JSON, a question and the expected answer (in AK-DATA)."
  # the feature examples: one part of the format each
  for i in $("$BIN" example --list --features --no-color | awk '/^ *[0-9]+ / {print $1}'); do
    title=$("$BIN" example "$i" --no-color | sed -n 3p)
    shows=$("$BIN" example "$i" --no-color | awk 'NR>3 && NF==0 {exit} NR>3 {print}' | tr '\n' ' ')
    echo
    echo "## $i. $title"
    echo
    echo "$shows"
    echo
    echo '```akd'
    "$BIN" example "$i" --raw
    echo '```'
    echo
    echo '```json'
    "$BIN" example "$i" --raw | "$BIN" -t json-min
    echo '```'
    echo
    "$BIN" example "$i" --prompt --raw | awk '/^Question:/ {print "**" $1 "**" substr($0, 10)}'
    echo
    echo '```akd'
    "$BIN" example "$i" --prompt --no-color | awk '/EXPECTED ANSWER/ {on=1; next} on && /^next:/ {exit} on && NF {print}'
    echo '```'
  done
} > "$OUT/examples.md"

echo "Written $OUT/spec.md and $OUT/examples.md"
