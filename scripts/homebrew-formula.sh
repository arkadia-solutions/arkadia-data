#!/usr/bin/env bash
# Homebrew formula for the release archives of ./VERSION, from their .sha256
# files (made by scripts/release.sh). The release workflow writes it to the
# tap arkadia-solutions/homebrew-tap as Formula/ak-data.rb:
#
#   scripts/homebrew-formula.sh [dir]  > Formula/ak-data.rb   # dir: dist/release
#
# brew install arkadia-solutions/tap/ak-data then downloads the binary for
# the machine (macOS universal, Linux x86_64 / arm64) — no Rust needed.
set -euo pipefail
cd "$(dirname "$0")/.."
dir=${1:-dist/release}
version=$(tr -d ' \n' < VERSION)
repo=${GITHUB_REPOSITORY:-arkadia-solutions/arkadia-data}
base="https://github.com/$repo/releases/download/v$version"

sum() {
  local f="$dir/ak-data-$version-$1.tar.gz.sha256"
  [[ -f $f ]] || { echo "missing $f (run scripts/release.sh on that platform)" >&2; exit 1; }
  cut -d' ' -f1 < "$f"
}

cat <<RUBY
# Generated by scripts/homebrew-formula.sh (arkadia-data) for v$version.
class AkData < Formula
  desc "AK-DATA (Arkadia Data Format): lossless, token-efficient JSON for LLMs"
  homepage "https://arkadia.solutions/akdata"
  version "$version"
  license "MIT"

  on_macos do
    url "$base/ak-data-$version-macos-universal.tar.gz"
    sha256 "$(sum macos-universal)"
  end

  on_linux do
    on_intel do
      url "$base/ak-data-$version-linux-x86_64.tar.gz"
      sha256 "$(sum linux-x86_64)"
    end
    on_arm do
      url "$base/ak-data-$version-linux-arm64.tar.gz"
      sha256 "$(sum linux-arm64)"
    end
  end

  def install
    bin.install "ak-data"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ak-data --version")
    assert_equal "<a:number>(1)", pipe_output("#{bin}/ak-data -c", '{"a":1}').strip
  end
end
RUBY
